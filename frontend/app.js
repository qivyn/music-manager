/* =========================================================
   搜索
========================================================= */

function matchesSearch(music, clips, query) {

    if (!query) {
        return true;
    }

    query = query.toLowerCase();

    const musicText = [

        music.name,
        music.fileName,
        music.album,
        music.artist,
        music.genre,
        music.year,
        music.path,
        ...(music.tags || [])

    ]
        .join(" ")
        .toLowerCase();


    if (musicText.includes(query)) {
        return true;
    }


    for (const clip of clips) {

        const clipText = [

            clip.name,
            ...(clip.tags || [])

        ]
            .join(" ")
            .toLowerCase();

        if (clipText.includes(query)) {
            return true;
        }
    }

    return false;
}


/* =========================================================
   获取当前音乐
========================================================= */

async function getCurrentMusicList(allMusic, clips) {

    let music = [...allMusic];
    const clipsByMusic = new Map();
    clips.forEach(clip => {
        if (!clipsByMusic.has(clip.musicId)) clipsByMusic.set(clip.musicId, []);
        clipsByMusic.get(clip.musicId).push(clip);
    });


    if (state.currentView === "recent") {

        if (state.recentMode === "used") {

            /* 最近使用：按使用历史打点排序 */
            music = music
                .filter(item => item.lastPlayedAt)
                .sort((a, b) => (b.lastPlayedAt || 0) - (a.lastPlayedAt || 0))
                .slice(0, 100);

        } else {

            music.sort(
                (a, b) => b.createdAt - a.createdAt
            );

            music = music.slice(0, 100);
        }
    }


    if (state.currentView === "clips") {

        const musicIds = new Set(
            clips.map(c => c.musicId)
        );

        music = music.filter(
            m => musicIds.has(m.id)
        );
    }


    if (state.currentView === "albums") {

        // 仍显示音乐，下面会按照 album 排序
        music.sort(
            (a, b) =>
                (a.album || "")
                    .localeCompare(
                        b.album || "",
                        "zh-CN"
                    )
        );
    }


    if (state.currentView.startsWith("tag:")) {

        const tagId = Number(state.currentView.substring(4));

        music = music.filter(m => {

            const musicHas =
                (m.tagIds || []).includes(tagId);

            const musicClips = clipsByMusic.get(m.id) || [];

            const clipHas =
                musicClips.some(
                    c =>
                        (c.tagIds || []).includes(tagId)
                );

            return musicHas || clipHas;
        });
    }


    const result = [];

    for (const m of music) {

        const mClips = clipsByMusic.get(m.id) || [];

        if (
            matchesSearch(
                m,
                mClips,
                state.search
            ) && matchesActiveTags(m, mClips)
        ) {
            result.push(m);
        }
    }

    return result;
}


